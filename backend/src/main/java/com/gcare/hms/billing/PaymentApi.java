package com.gcare.hms.billing;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.gcare.hms.billing.BillingApi.ServiceStatus;
import com.gcare.hms.configuration.ConfigApi.BrandingView;
import com.gcare.hms.encounter.EncounterApi.UserRef;
import com.gcare.hms.patient.PatientApi.PatientSummary;
import jakarta.validation.Valid;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/**
 * Payment methods, payments, receipts and cashier shifts (task 4.3; FR-018; docs/19 §4). Money is
 * {@link BigDecimal} in the invoice's currency; nothing is converted.
 */
public final class PaymentApi {

  private PaymentApi() {}

  private static final String CODE = "^[A-Z0-9][A-Z0-9_-]*$";

  public enum ShiftStatus {
    OPEN,
    CLOSED,
    REVIEWED
  }

  /** Receipt layout is basic and PROVISIONAL until the finance owner approves it (docs/19). */
  public static final String RECEIPT_FORMAT = "PROVISIONAL";

  // --- methods ---------------------------------------------------------------------------------

  public record CreateMethodRequest(
      @NotBlank
          @Size(max = 30)
          @Pattern(regexp = CODE, message = "use capital letters, digits, - or _")
          String code,
      @NotBlank @Size(max = 100) String name,
      @NotNull @JsonProperty("is_cash") Boolean isCash) {}

  public record UpdateMethodRequest(
      long version, @NotBlank @Size(max = 100) String name, @NotNull ServiceStatus status) {}

  public record MethodView(
      UUID id,
      String code,
      String name,
      @JsonProperty("is_cash") boolean isCash,
      ServiceStatus status,
      long version) {}

  // --- payments --------------------------------------------------------------------------------

  public record RecordPaymentRequest(
      /** Generated by the browser once per payment form; a retry with the same key is safe. */
      @NotNull @JsonProperty("idempotency_key") UUID idempotencyKey,
      @NotNull @JsonProperty("method_id") UUID methodId,
      @NotNull @DecimalMin(value = "0", inclusive = false) BigDecimal amount,
      @Size(max = 100) String reference) {}

  public record MethodRef(
      UUID id, String code, String name, @JsonProperty("is_cash") boolean isCash) {}

  public record PaymentView(
      UUID id,
      @JsonProperty("invoice_id") UUID invoiceId,
      @JsonProperty("shift_id") UUID shiftId,
      MethodRef method,
      String currency,
      BigDecimal amount,
      @JsonProperty("balance_after") BigDecimal balanceAfter,
      String reference,
      @JsonProperty("receipt_number") String receiptNumber,
      @JsonProperty("received_by") UserRef receivedBy,
      @JsonProperty("received_at") Instant receivedAt) {}

  public record ReceiptView(
      String format,
      /** PAYMENT (money received) or REFUND (money paid back; task 4.4). */
      String kind,
      @JsonProperty("receipt_number") String receiptNumber,
      @JsonProperty("facility_name") String facilityName,
      /** Approved facility branding and receipt text (task 5.2). */
      BrandingView branding,
      @JsonProperty("received_at") Instant receivedAt,
      PatientSummary patient,
      @JsonProperty("invoice_number") String invoiceNumber,
      @JsonProperty("invoice_total") BigDecimal invoiceTotal,
      String currency,
      BigDecimal amount,
      @JsonProperty("method_name") String methodName,
      String reference,
      @JsonProperty("balance_after") BigDecimal balanceAfter,
      @JsonProperty("cashier_name") String cashierName) {}

  // --- shifts ----------------------------------------------------------------------------------

  public record OpenShiftRequest(@NotNull @JsonProperty("facility_id") UUID facilityId) {}

  public record CountEntry(
      @NotBlank @Pattern(regexp = "^[A-Z]{3}$", message = "must be an ISO 4217 code")
          String currency,
      @NotNull @DecimalMin("0") BigDecimal counted) {}

  public record CloseShiftRequest(
      long version, @NotNull List<@Valid CountEntry> counts, @Size(max = 500) String note) {}

  public record ReviewRequest(long version, @NotBlank @Size(max = 500) String note) {}

  public record CurrencyAmount(String currency, BigDecimal amount) {}

  public record MethodTotal(
      @JsonProperty("method_code") String methodCode,
      @JsonProperty("method_name") String methodName,
      @JsonProperty("is_cash") boolean isCash,
      String currency,
      BigDecimal amount,
      int payments) {}

  public record CountView(
      String currency, BigDecimal expected, BigDecimal counted, BigDecimal difference) {}

  public record ShiftView(
      UUID id,
      @JsonProperty("facility_id") UUID facilityId,
      UserRef cashier,
      ShiftStatus status,
      @JsonProperty("opened_at") Instant openedAt,
      @JsonProperty("closed_at") Instant closedAt,
      @JsonProperty("close_note") String closeNote,
      @JsonProperty("reviewed_by") UserRef reviewedBy,
      @JsonProperty("reviewed_at") Instant reviewedAt,
      @JsonProperty("review_note") String reviewNote,
      /** Payments in the shift by method and currency. */
      List<MethodTotal> totals,
      /** Refunds paid out in the shift by method and currency (task 4.4). */
      List<MethodTotal> refunds,
      /** Cash that should be in the drawer, per currency: cash payments minus cash refunds. */
      @JsonProperty("expected_cash") List<CurrencyAmount> expectedCash,
      /** Counted at close; empty while open. */
      List<CountView> counts,
      long version) {}
}
